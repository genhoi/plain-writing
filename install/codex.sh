#!/usr/bin/env bash
# Подключить скилл к Codex: строка в ~/.codex/AGENTS.md со ссылкой на SKILL.md.
# Использование: install/codex.sh

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

CODEX_HOME="${CODEX_HOME:-$HOME/.codex}"
# Прежняя строка включала «отчёт мне», и Codex читал скилл перед каждым итоговым ответом,
# в том числе в автоматических запусках, где текста для людей нет.
if [ -f "$CODEX_HOME/AGENTS.md" ] && grep -qF -- "Прочитай файл перед тем, как писать такой текст." "$CODEX_HOME/AGENTS.md"; then
  echo "в $CODEX_HOME/AGENTS.md прежняя строка про скилл: из-за «отчёт мне» Codex читает его перед каждым ответом." >&2
  echo "Замените её строкой «…Читай файл, когда начинаешь писать такой текст, а не в начале каждой задачи…»." >&2
fi
ensure_line "$CODEX_HOME/AGENTS.md" "plain-writing" \
  "Текст, который прочитают без нашего чата (задача в трекере, описание MR, комментарий в ревью, сообщение коллеге), пиши по правилам из \`$SKILL_FILE\`. Читай файл, когда начинаешь писать такой текст, а не в начале каждой задачи: для ответа в чате и для отчёта другому агенту он не нужен."
